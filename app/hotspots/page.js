"use client";

import { useState, useEffect, useMemo } from "react";
import HotspotMap from "../components/HotspotMap";

const CATEGORY_FILTERS = [
  { value: "all", label: "All Sectors" },
  { value: "roads", label: "Roads & Potholes", icon: "🛣️" },
  { value: "water_supply", label: "Water Supply", icon: "🚰" },
  { value: "sanitation", label: "Sanitation", icon: "🧹" },
  { value: "streetlights", label: "Streetlights", icon: "💡" },
  { value: "drainage", label: "Drainage", icon: "🌊" },
  { value: "health_facility", label: "Health Facility", icon: "🏥" },
  { value: "public_transport", label: "Public Transit", icon: "🚌" },
  { value: "solid_waste", label: "Solid Waste", icon: "🗑️" },
];

export default function HotspotsPage() {
  const [hotspots, setHotspots] = useState([]);
  const [loading, setLoading] = useState(true);
  const [selectedCategory, setSelectedCategory] = useState("all");
  const [selectedHotspotId, setSelectedHotspotId] = useState(null);

  useEffect(() => {
    async function fetchHotspots() {
      try {
        const res = await fetch("/api/hotspots");
        const data = await res.json();
        setHotspots(data.hotspots || []);
      } catch (err) {
        console.error("Failed to load hotspots:", err);
      } finally {
        setLoading(false);
      }
    }
    fetchHotspots();
  }, []);

  const filteredHotspots = useMemo(() => {
    if (selectedCategory === "all") return hotspots;
    return hotspots.filter((h) => h.category === selectedCategory);
  }, [hotspots, selectedCategory]);

  const fundedCount = hotspots.filter((h) => h.funding_status === "funded").length;
  const queuedCount = hotspots.filter((h) => h.funding_status === "queued").length;

  return (
    <div style={{ maxWidth: "1320px", margin: "100px auto 80px", padding: "0 2rem" }}>
      {/* Page Header */}
      <div style={{ marginBottom: "2rem" }}>
        <span className="brand-pill" style={{ marginBottom: "0.5rem", display: "inline-block" }}>
          GEOSPATIAL INTELLIGENCE
        </span>
        <h1 style={{ fontSize: "2.4rem", fontWeight: 700, margin: "0.25rem 0" }}>
          City-Wide Infrastructure Hotspots
        </h1>
        <p style={{ color: "#666", fontSize: "0.95rem" }}>
          Deduplicated municipal clusters generated by Gemini vector embeddings (within 2km radius).
        </p>
      </div>

      {/* Metric Cards */}
      <div style={{ display: "grid", gridTemplateColumns: "repeat(auto-fit, minmax(200px, 1fr))", gap: "1.2rem", marginBottom: "2rem" }}>
        <div className="scaffold-card" style={{ padding: "1.2rem 1.5rem" }}>
          <div style={{ fontSize: "0.78rem", color: "#666", textTransform: "uppercase", fontWeight: 600 }}>Total Hotspots</div>
          <div style={{ fontSize: "2rem", fontWeight: 700, color: "#111" }}>{hotspots.length}</div>
        </div>
        <div className="scaffold-card" style={{ padding: "1.2rem 1.5rem" }}>
          <div style={{ fontSize: "0.78rem", color: "#666", textTransform: "uppercase", fontWeight: 600 }}>Funded Tenders</div>
          <div style={{ fontSize: "2rem", fontWeight: 700, color: "#059669" }}>{fundedCount}</div>
        </div>
        <div className="scaffold-card" style={{ padding: "1.2rem 1.5rem" }}>
          <div style={{ fontSize: "0.78rem", color: "#666", textTransform: "uppercase", fontWeight: 600 }}>Pending Queue</div>
          <div style={{ fontSize: "2rem", fontWeight: 700, color: "#d97706" }}>{queuedCount}</div>
        </div>
        <div className="scaffold-card" style={{ padding: "1.2rem 1.5rem" }}>
          <div style={{ fontSize: "0.78rem", color: "#666", textTransform: "uppercase", fontWeight: 600 }}>Deduplication Radius</div>
          <div style={{ fontSize: "2rem", fontWeight: 700, color: "#2563eb" }}>2.0 km</div>
        </div>
      </div>

      {/* Category Filter Chips */}
      <div style={{ display: "flex", gap: "0.5rem", overflowX: "auto", paddingBottom: "0.75rem", marginBottom: "1.5rem" }}>
        {CATEGORY_FILTERS.map((cat) => (
          <button
            key={cat.value}
            onClick={() => setSelectedCategory(cat.value)}
            className={`chip-stitch ${selectedCategory === cat.value ? "active" : ""}`}
            style={{ whiteSpace: "nowrap" }}
          >
            {cat.icon && <span>{cat.icon}</span>}
            <span>{cat.label}</span>
          </button>
        ))}
      </div>

      {/* Main Map & Cluster List Split */}
      <div style={{ display: "grid", gridTemplateColumns: "1.3fr 1fr", gap: "2rem", alignItems: "start" }}>
        {/* Left: Map */}
        <div className="scaffold-card" style={{ padding: "1.5rem" }}>
          <div className="card-top-row" style={{ marginBottom: "1rem" }}>
            <div>
              <h3 style={{ fontSize: "1.15rem", fontWeight: 600 }}>Geospatial Distribution</h3>
              <p style={{ color: "#666", fontSize: "0.82rem" }}>
                Click a pin to view cluster corroboration details
              </p>
            </div>
            <div style={{ display: "flex", gap: "0.4rem" }}>
              <span className="badge-status badge-funded-stitch">🟢 Funded</span>
              <span className="badge-status badge-queued-stitch">🟠 Queued</span>
            </div>
          </div>
          <HotspotMap
            hotspots={filteredHotspots}
            selectedId={selectedHotspotId}
            onSelect={(id) => setSelectedHotspotId(id)}
            height="560px"
          />
        </div>

        {/* Right: Cluster Cards */}
        <div style={{ display: "flex", flexDirection: "column", gap: "1rem" }}>
          <div style={{ fontSize: "0.95rem", fontWeight: 600, color: "#111" }}>
            Active Hotspots ({filteredHotspots.length})
          </div>

          {filteredHotspots.length === 0 ? (
            <div className="scaffold-card" style={{ textAlign: "center", padding: "3rem 1.5rem", color: "#888" }}>
              No hotspots found for this sector filter.
            </div>
          ) : (
            filteredHotspots.map((hs) => {
              const isSelected = selectedHotspotId === hs.id;
              const isFunded = hs.funding_status === "funded";

              return (
                <div
                  key={hs.id}
                  onClick={() => setSelectedHotspotId(hs.id)}
                  className="scaffold-card"
                  style={{
                    padding: "1.2rem",
                    cursor: "pointer",
                    border: isSelected ? "2px solid #000000" : "1px solid #e7e7e4",
                    background: isSelected ? "#fdf8f8" : "#ffffff",
                    transition: "all 0.15s ease",
                  }}
                >
                  <div style={{ display: "flex", justifyContent: "space-between", alignItems: "flex-start", marginBottom: "0.5rem" }}>
                    <div>
                      <span style={{ fontSize: "0.85rem", fontWeight: 600, textTransform: "capitalize" }}>
                        {hs.category?.replace(/_/g, " ")} Cluster
                      </span>
                      <div style={{ color: "#888", fontSize: "0.78rem", fontFamily: "var(--font-mono)" }}>
                        {hs.id}
                      </div>
                    </div>
                    <span className={`badge-status ${isFunded ? "badge-funded-stitch" : "badge-queued-stitch"}`}>
                      {isFunded ? "✓ Funded" : "⏳ Queued"}
                    </span>
                  </div>

                  <div style={{ display: "flex", justifyContent: "space-between", alignItems: "center", marginTop: "0.75rem", fontSize: "0.82rem", color: "#4b5563" }}>
                    <span>👥 {hs.corroboration_count || 1} Citizen Report{(hs.corroboration_count || 1) > 1 ? "s" : ""}</span>
                    <span>Priority Score: <strong style={{ color: "#2563eb" }}>{hs.priority_score?.toFixed(1)}</strong></span>
                    <span>Cost: <strong>₹{hs.sample_budget_used || 10}L</strong></span>
                  </div>
                </div>
              );
            })
          )}
        </div>
      </div>
    </div>
  );
}
